"""VectorCornerPin's pins as the Nuke 17.0 Reference Guide describes them (lane 9, 2D behaviour step G): the four `user` pins, the `To` pins,
the `From` quad and the Output choice.

The guide: the node "takes paint or an image from a reference frame and propagates it through the rest of the sequence using the motion vectors
generated by the SmartVector node", like CornerPin2D. `user1` to `user4` "control the position of the pins at the current keyframe"; `to1` to `to4`
"display the position of the pins at the current frame, once you've set a user keyframe"; the From quad is the corner pin's source (pin 1 the
bottom left, 2 the bottom right, 3 the top right, 4 the top left); Output is "warped src", "st-map" ("the st-map for the warp from the reference
frame to the current frame") or "st-map inverse" ("the warp from the current frame to the reference frame").

What the guide leaves open, and this module therefore fixes:

* points are in Nuke's pixel space (x to the right, y up from the bottom edge, a pixel's centre at half integers). The defaults 0 0, 100 0, 100 100
  and 0 100 stand for the format's four corners, as the corner defaults of the older node did (the format is not known when the node is made);
* the pins at the current frame are the `user` pins moved by the SmartVector motion at each pin, from the reference frame to the current one. With no
  SmartVector wired, or at the reference frame, they are the `user` pins. The warp takes the From quad onto them;
* the `To` pins are the baked pins: Bake Corners (a render over the frame range) writes them. A render never writes a parameter, so they only
  hold what was typed or baked; they act when `use_baked` is on (the Bake Corners button sets it) and then replace the pins the vectors give;
* an st-map holds r = (x + 0.5) / width and g = 1 - (y + 0.5) / height of the source pixel each output pixel takes (the STMap node's own
  convention), b = 0 and alpha 1 where the warp reaches the picture and 0 elsewhere.

An older document's node (`legacy_vectorcornerpin` 1) keeps what it did: the four `corner` points are both the source quad and the pins' starting
points, the vectors displace them and a SmartVector must be wired.
"""
from __future__ import annotations

import numpy as np

CORNERS = (1, 2, 3, 4)
SENTINEL = ((0.0, 0.0), (100.0, 0.0), (100.0, 100.0), (0.0, 100.0))
OUTPUT_MODES = ("warped src", "st-map", "st-map inverse")
_SIDES = ("user", "to", "from")
NEW = {"legacy_vectorcornerpin": 0, "output_mode": "warped src", "use_baked": 0}
for _side in _SIDES:
    for _i, (_x, _y) in zip(CORNERS, SENTINEL):
        NEW[f"{_side}{_i}_x"] = _x
        NEW[f"{_side}{_i}_y"] = _y
UPGRADE = {"legacy_vectorcornerpin": 1, "output_mode": "warped src", "use_baked": 0}
for _side in _SIDES:
    for _i, (_x, _y) in zip(CORNERS, SENTINEL):
        UPGRADE[f"{_side}{_i}_x"] = _x
        UPGRADE[f"{_side}{_i}_y"] = _y
POINT_PARAMS = tuple(f"{side}{i}_{axis}" for side in _SIDES for i in CORNERS for axis in ("x", "y"))


def is_legacy(p):
    return bool(int(p.get("legacy_vectorcornerpin", 1)))


def points(p, side, width, height, tier=1):
    """The four points of `side` ("user", "to" or "from") in picture index space (x right, row down, a pixel's index at its centre), as (4, 2).
    The sentinel stands for the format's corners; parameters arrive divided by the tier."""
    raw = np.asarray([[float(p[f"{side}{i}_x"]), float(p[f"{side}{i}_y"])] for i in CORNERS], np.float64)
    if np.allclose(raw, np.asarray(SENTINEL) / float(tier)):
        raw = np.asarray([[0.0, 0.0], [width, 0.0], [width, height], [0.0, height]], np.float64)
    return np.stack([raw[:, 0] - 0.5, (height - raw[:, 1]) - 0.5], axis=1)


def st_map(matrix, width, height, inverse=False):
    """The st-map of the warp `matrix` (source index space to output index space): for each output pixel the source pixel it takes
    (`inverse` False), or for each source pixel the output pixel it lands on (`inverse` True)."""
    yy, xx = np.mgrid[:height, :width].astype(np.float64)
    m = np.asarray(matrix, np.float64)
    if not inverse:
        m = np.linalg.inv(m)
    den = m[2, 0] * xx + m[2, 1] * yy + m[2, 2]
    den = np.where(np.abs(den) < 1e-10, 1e-10, den)
    sx = (m[0, 0] * xx + m[0, 1] * yy + m[0, 2]) / den
    sy = (m[1, 0] * xx + m[1, 1] * yy + m[1, 2]) / den
    out = np.zeros((height, width, 4), np.float32)
    out[..., 0] = (sx + 0.5) / width
    out[..., 1] = 1.0 - (sy + 0.5) / height
    inside = (sx >= -0.5) & (sx <= width - 0.5) & (sy >= -0.5) & (sy <= height - 0.5)
    out[..., 3] = inside.astype(np.float32)
    out[~inside] = 0.0
    return out

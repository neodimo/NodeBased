"""VectorDistort as the Nuke 17.0 Reference Guide describes it (lane 9, 2D behaviour step N): Hold Frame, Output, Filter and the channels selector.

The guide: the node "takes the paint from a reference frame and propagates it through the rest of the sequence using the motion vectors generated by
the SmartVector node".

* Hold Frame (`hold_frame`, on): "the reference frame is warped instead of the current frame. This is equivalent to inserting a FrameHold node into the
  node tree after the source." Off: "the current frame is warped instead of the reference frame": the source at the current frame is carried back
  to the reference frame with the vectors reversed, the way a stabilise does. The vectors give, for each pixel, where the reference frame's content has
  moved to; the reversed warp reads the current frame at each pixel's own position plus that vector. The paint fade (`fade_frames`, NodeBased's own)
  belongs to the held paint and is not applied to the current frame.
* Output (`output_mode`): "warped src", or "st-map" ("the st-map for the warp from the reference frame to the current frame") or "st-map inverse" ("the
  warp from the current frame to the reference frame"). The st-map follows the STMap node's convention (and VectorCornerPin's): r = (x + 0.5) / width,
  g = 1 - (y + 0.5) / height of the source pixel an output pixel takes, b = 0, alpha 1 where the warp reaches the picture and 0 elsewhere. A map is not a
  picture, so no mask, mix or fade acts on it.
* Filter (`image_filter`, Cubic): "the filtering algorithm to apply the warp to the image, similar to that of the filters used in the IDistort and STMap
  nodes": the Transform group's list (nodebased/transformbehaviour.py), Notch not offered. A node saved before keeps bilinear sampling.
* Channels: the warp reaches only the selected channels; the rest pass through (the shared strip in nodebased/ops2d_chrome.py).

Frame Distance is not built. In Nuke SmartVector stores several vector sets, for hops of 1, 2, 4 ... 64 frames, and the knob picks one ("the maximum value for
this control is passed down the node tree from a SmartVector node's frame distance control"). NodeBased's SmartVector stores one accumulated set per
frame, re-anchored every `reanchor_interval` frames, so there is no second set to pick; the knob is listed `unsupported` in the mapping.

An older document's node (`legacy_vectordistort` 1) keeps what it did: it warps the reference frame with bilinear sampling and has no output choice.
"""
from __future__ import annotations

import numpy as np

OUTPUT_MODES = ("warped src", "st-map", "st-map inverse")
NEW = {"legacy_vectordistort": 0, "hold_frame": 1, "output_mode": "warped src", "image_filter": "cubic"}
UPGRADE = {"legacy_vectordistort": 1, "hold_frame": 1, "output_mode": "warped src", "image_filter": "bilinear"}
LIMITS = {"legacy_vectordistort": (0, 1), "hold_frame": (0, 1)}


def is_legacy(p):
    return bool(int(p.get("legacy_vectordistort", 1)))


def st_map(field, inverse=False):
    """The st-map of a reference-to-current displacement `field` (rows, columns, 2; the picture-index vector each pixel's content moves by).

    Not inverse: for each output pixel the source pixel it takes (the pixel `field` carried onto it). Inverse: for each pixel of the reference the
    pixel it lands on at the current frame."""
    h, w = field.shape[:2]
    yy, xx = np.mgrid[:h, :w].astype(np.float64)
    sign = 1.0 if inverse else -1.0
    sx = xx + sign * field[..., 0]
    sy = yy + sign * field[..., 1]
    out = np.zeros((h, w, 4), np.float32)
    out[..., 0] = (sx + 0.5) / w
    out[..., 1] = 1.0 - (sy + 0.5) / h
    inside = (sx >= -0.5) & (sx <= w - 0.5) & (sy >= -0.5) & (sy <= h - 0.5)
    out[..., 3] = inside.astype(np.float32)
    out[~inside] = 0.0
    return out


def warp(p, held, current, field, resample, blur):
    """The picture VectorDistort outputs (before mask and mix) for a modern node.

    `held` is the reference frame's picture, `current` the source at this frame, `field` the reference-to-current displacement, `resample` the
    evaluator's filtered sampler `(src, sx, sy, filter)`, and `blur` the box blur the Blur Size knob asks for (a function of the picture)."""
    mode = str(p.get("output_mode", "warped src"))
    if mode != "warped src":
        return st_map(field, inverse=mode == "st-map inverse"), False
    h, w = field.shape[:2]
    yy, xx = np.mgrid[:h, :w].astype(np.float32)
    hold = bool(int(p.get("hold_frame", 1)))
    image, flow = (held, field) if hold else (current, -field)
    x, y = xx - flow[..., 0], yy - flow[..., 1]
    result = resample(image, x, y, str(p.get("image_filter", "cubic")))
    valid = (x >= 0) & (x <= w - 1) & (y >= 0) & (y <= h - 1)
    result = np.where(valid[..., None], result, 0).astype(np.float32)
    return blur(result), hold

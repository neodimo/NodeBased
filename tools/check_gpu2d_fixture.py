#!/usr/bin/env python3
"""Compare the GPU 2D island with the CPU kernels on the realistic playback comp.

Runs `tests/fixtures/playback_comp.nbcomp` (Read -> Grade -> Transform -> Blur -> Merge ->
ColorCorrect, with a separate Read background and a Roto matte) on two fresh evaluators, one
with the opt-in GPU island and one on the CPU kernels, and reports per frame and overall:

* max / mean / p99 absolute error, and the largest `abs(gpu-cpu) / (2e-5 + 2e-5*abs(cpu))` over
  every finite channel (the spike's pixel gate passes when that ratio is at most 1),
* the island's counters (uploads, downloads, intermediate readbacks, passes, bytes, timings).

The EXR sources are generated by `tools/benchmark_2d_playback.py --generate-inputs` (pass the
directory it filled); this tool never writes them.

    python tools/check_gpu2d_fixture.py --inputs "$NB_RUN/plates" --size 1080p --frames 1 12 24 36 48 \
        --adapter default --output "$NB_RUN/pixels.json"
"""
from __future__ import annotations

import argparse
import json
import os
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
FIXTURE = ROOT / "tests/fixtures/playback_comp.nbcomp"
TOLERANCE_ABS = 2e-5
TOLERANCE_REL = 2e-5


def fixture_document(plate_pattern, background_pattern, width, height, last=None, path=FIXTURE):
    """The fixture with its sources pointed at generated plates and its Roto scaled to the frame,
    exactly as `tools/benchmark_2d_playback.py` prepares it. `last` extends the frame range only."""
    sys.path.insert(0, str(ROOT))
    from nodebased.core import load_document
    doc = load_document(path)
    doc["nodes"]["plate"]["params"]["path"] = str(pathlib.Path(plate_pattern).resolve())
    doc["nodes"]["background"]["params"]["path"] = str(pathlib.Path(background_pattern).resolve())
    sx, sy = width / 1920, height / 1080
    doc["nodes"]["roto"]["params"].update(width=width, height=height)
    for shape in doc["node_data"]["roto"]["shapes"]:
        for point in shape["points"]:
            for field, scale in (("x", sx), ("y", sy), ("in_x", sx), ("out_x", sx), ("in_y", sy), ("out_y", sy)):
                scalar = point[field]
                if isinstance(scalar, dict):
                    scalar["value"] *= scale
                    for key in scalar.get("curve", {}).get("keys", []):
                        key["value"] *= scale
                else:
                    point[field] = scalar * scale
    if last is not None:
        doc["time"]["last"] = int(last)
    return doc


def compare_arrays(gpu, cpu):
    """Error statistics over the finite channels, and whether non-finite values agree."""
    gpu = np.asarray(gpu, np.float64)
    cpu = np.asarray(cpu, np.float64)
    finite = np.isfinite(cpu) & np.isfinite(gpu)
    diff = np.abs(gpu - cpu)[finite]
    allowed = TOLERANCE_ABS + TOLERANCE_REL * np.abs(cpu[finite])
    ratio = diff / allowed
    same_nonfinite = bool(np.array_equal(np.isfinite(cpu), np.isfinite(gpu)))
    if diff.size == 0:
        return {"channels": 0, "nonfinite_match": same_nonfinite}
    return {"channels": int(diff.size), "max_abs": float(diff.max()), "mean_abs": float(diff.mean()),
            "p99_abs": float(np.percentile(diff, 99)), "max_gate_ratio": float(ratio.max()),
            "violations": int((ratio > 1.0).sum()), "nonfinite_match": same_nonfinite}


def run_check(inputs, size, frames, adapter, budget_mb, targets=("merge", "colorcorrect"), last=None, tier=1):
    sys.path.insert(0, str(ROOT))
    from nodebased import gpu2d
    from nodebased.imaging import Evaluator
    width, height = (1920, 1080) if size == "1080p" else (3840, 2160) if size == "4k" else tuple(int(v) for v in size.split("x"))
    inputs = pathlib.Path(inputs)
    doc = fixture_document(inputs / "plate.%04d.exr", inputs / "background.%04d.exr", width, height, last)
    backend = gpu2d.GPU2D.open(adapter, budget_mb << 20)
    if backend is None:
        return {"error": f"no GPU 2D backend on adapter {adapter!r}: {gpu2d.GPU2D.open_error}"}
    report = {"adapter": backend.describe(), "size": [width, height], "tier": tier, "frames": [], "worst": {}}
    for target in targets:
        for frame in frames:
            cpu = Evaluator().evaluate_raster(doc, target, frame=frame, tier=tier)
            evaluator = Evaluator()
            evaluator.gpu2d = backend
            before = backend.counters.snapshot()
            result = evaluator.evaluate_raster(doc, target, frame=frame, tier=tier)
            counters = gpu2d.Counters.delta(backend.counters.snapshot(), before)
            report["frames"].append({
                "target": target, "frame": frame,
                "windows_match": bool(result.data == cpu.data and result.display == cpu.display),
                "error": compare_arrays(result.pixels, cpu.pixels), "counters": counters})
    for target in targets:
        rows = [r for r in report["frames"] if r["target"] == target]
        errors = [r["error"] for r in rows if "max_abs" in r["error"]]
        report["worst"][target] = {
            "max_abs": max((e["max_abs"] for e in errors), default=None),
            "mean_abs": float(np.mean([e["mean_abs"] for e in errors])) if errors else None,
            "p99_abs": max((e["p99_abs"] for e in errors), default=None),
            "max_gate_ratio": max((e["max_gate_ratio"] for e in errors), default=None),
            "violations": sum(e["violations"] for e in errors),
            "all_windows_match": all(r["windows_match"] for r in rows),
            "downloads_per_frame": sorted({r["counters"]["downloads"] for r in rows}),
            "intermediate_readbacks": sum(r["counters"]["intermediate_readbacks"] for r in rows),
            "cpu_boundaries": sorted({b for r in rows for b in r["counters"]["cpu_boundaries"]}),
        }
    report["gate"] = "pass" if all(w["violations"] == 0 and w["all_windows_match"] and w["intermediate_readbacks"] == 0
                                   and w["downloads_per_frame"] == [1] and not w["cpu_boundaries"]
                                   for w in report["worst"].values()) else "fail"
    report["gate_rule"] = f"every finite channel abs(gpu-cpu) <= {TOLERANCE_ABS} + {TOLERANCE_REL}*abs(cpu)"
    return report


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--inputs", required=True, type=pathlib.Path, help="directory holding plate.%%04d.exr and background.%%04d.exr")
    parser.add_argument("--size", default="1080p", help="1080p, 4k or WIDTHxHEIGHT (matching the generated inputs)")
    parser.add_argument("--frames", type=int, nargs="+", default=[1, 24, 48])
    parser.add_argument("--adapter", default="default", choices=("default", "discrete", "integrated", "cpu"))
    parser.add_argument("--budget-mb", type=int, default=1024)
    parser.add_argument("--tier", type=int, default=1)
    parser.add_argument("--last", type=int, help="extend the frame range (curves extrapolate)")
    parser.add_argument("--output", type=pathlib.Path)
    args = parser.parse_args()
    os.environ.setdefault("QT_QPA_PLATFORM", "offscreen")
    report = run_check(args.inputs, args.size, args.frames, args.adapter, args.budget_mb, last=args.last, tier=args.tier)
    if args.output:
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(report, indent=1) + "\n")
    print(json.dumps({"adapter": report.get("adapter", {}).get("device"), "gate": report.get("gate"),
                      "worst": report.get("worst"), "error": report.get("error")}, indent=1))
    return 0 if report.get("gate") == "pass" else 1


if __name__ == "__main__":
    sys.exit(main())

"""Does the video model follow the exported camera? Dolly and pan paths on the demo scene, two models.

For each path (a straight dolly forward by one scene unit, a pan of 20 degrees with the position fixed, a truck
sideways by one unit, a pan plus dolly) the demo shot's graph is built with that camera path, the SceneState and
ControlBundle are exported, the shot is generated by a provider with the same reference frame and seed, and the
verifier's camera check measures the camera the generated pictures show against the exported camera on every frame:

    python examples/demo_shot/benchmark_camera_following.py --work DIR --out DIR [--runs cameractrl:dolly,...]
                                                            [--translation-scale 1,0.5,0.25]

`--translation-scale` (comma list, repeatable) runs every CameraCtrl run once per scale as the sampler setting of that
name; a run is then named `cameractrl:dolly@0.25` (a run can also carry its own `@scale`). Without it the provider
chooses the scale from the reference frame's depth. `--floor PATHS` runs the camera check on the exported beauty
frames themselves, the score of a perfect follower (no GPU).

`cameractrl_svd` (CameraCtrl on SVD-XT) takes the camera and makes 25 frames at 576 x 320. `svd_image_video`
(step A, the control) ignores the camera and is limited to eight frames on this card, so its path covers the
same total move in eight frames, on a 16:9 plate. The camera check's measurement is kept in the report for a provider that
does not honour the camera; nothing here changes the verdict.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import sys
import time
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import shot  # noqa: E402
import run_by_hand  # noqa: E402

REPO = shot.HERE.parents[1]
sys.path.insert(0, str(REPO))
# CameraCtrl generates at 576 x 320. step A's adapter resizes to 1024 x 576 (16:9), so its control runs on the 16:9
# plate 576 x 324: a 576 x 320 plate would be stretched by 1.2 percent each way and the camera fit would read it
# as a rotation error on the reference frame itself.
SIZES = {"cameractrl": (576, 320), "svd": (576, 324)}
SEED = 7
MODELS = {"cameractrl": ("cameractrl_svd", 25, "NODEBASED_CAMERACTRL_RUN_INFO"),
          "svd": ("svd_image_video", 8, "NODEBASED_SVD_RUN_INFO")}
DOLLY_UNITS = 1.0
PAN_DEGREES = 20.0
TRUCK_UNITS = 1.0
PATHS = ("dolly", "pan", "truck", "pandolly")


def camera_keys(path, frames):
    """Camera parameters for each frame: the move spans the whole clip, whatever its length."""
    start = shot.CAMERA_START
    eye = np.array((start["tx"], start["ty"], start["tz"]))
    target = np.array((start["target_x"], start["target_y"], start["target_z"]))
    forward = (target - eye) / np.linalg.norm(target - eye)
    keys = {}
    for frame in range(1, frames + 1):
        t = (frame - 1) / max(frames - 1, 1)
        if path == "dolly":
            position, aim = eye + forward * DOLLY_UNITS * t, target + forward * DOLLY_UNITS * t
        elif path in ("pan", "pandolly"):
            angle = math.radians(PAN_DEGREES * t)  # a positive turn about +Y looks to the left
            rotation = np.array(((math.cos(angle), 0, math.sin(angle)), (0, 1, 0), (-math.sin(angle), 0, math.cos(angle))))
            position = eye + forward * DOLLY_UNITS * t if path == "pandolly" else eye
            aim = position + rotation @ (target - eye)
        elif path == "truck":
            right = np.cross(forward, (0.0, 1.0, 0.0))
            right /= np.linalg.norm(right)
            position, aim = eye + right * TRUCK_UNITS * t, target + right * TRUCK_UNITS * t
        else:
            raise ValueError(path)
        keys[frame] = dict(tx=position[0], ty=position[1], tz=position[2], target_x=aim[0], target_y=aim[1],
                           target_z=aim[2], roll=0.0, focal=shot.FOCAL)
    return keys


def static_camera_reference(keys):
    """What a camera that never leaves frame 1 would score against the path: the size of the move itself."""
    def parts(key):
        eye = np.array((key["tx"], key["ty"], key["tz"]))
        aim = np.array((key["target_x"], key["target_y"], key["target_z"])) - eye
        return eye, aim / np.linalg.norm(aim)
    first_eye, first_aim = parts(keys[1])
    rows = []
    for frame in sorted(keys)[1:]:
        eye, aim = parts(keys[frame])
        rows.append((float(np.linalg.norm(eye - first_eye)), float(np.degrees(np.arccos(np.clip(first_aim @ aim, -1, 1))))))
    return {"position_error_mean": float(np.mean([r[0] for r in rows])), "position_error_last": rows[-1][0],
            "rotation_error_degrees_mean": float(np.mean([r[1] for r in rows])), "rotation_error_degrees_last": rows[-1][1]}


def summarise(report, first_frame_is_reference=True):
    rows = []
    for frame in report["frames"]:
        camera = (frame.get("bindings") or {}).get("camera") or {}
        rows.append({"frame": frame.get("frame"), "position_error": camera.get("position_error_m"),
                     "rotation_error_degrees": camera.get("rotation_error_degrees"),
                     "fov_error_degrees": camera.get("fov_error_degrees"),
                     "tracker_landmarks": camera.get("tracker_landmarks"),
                     "reprojection_rms_pixels": camera.get("tracker_reprojection_rms_pixels"),
                     "reason": camera.get("reason")})
    moving = [r for r in rows[1:] if r["rotation_error_degrees"] is not None] if first_frame_is_reference else \
        [r for r in rows if r["rotation_error_degrees"] is not None]

    def stat(name, function):
        values = [r[name] for r in moving]
        return float(function(values)) if values else None
    return {"frames": len(rows), "solved_frames": len(moving),
            "rotation_error_degrees": {"mean": stat("rotation_error_degrees", np.mean),
                                       "max": stat("rotation_error_degrees", np.max),
                                       "last": moving[-1]["rotation_error_degrees"] if moving else None},
            "position_error": {"mean": stat("position_error", np.mean), "max": stat("position_error", np.max),
                               "last": moving[-1]["position_error"] if moving else None},
            "fov_error_degrees_mean": stat("fov_error_degrees", np.mean), "per_frame": rows}


def scene_tools():
    """The readers that turn an exported SceneState / ControlBundle artifact back into objects."""
    from nodebased.control_bundle import read_control_bundle
    from nodebased.loops import _unpack_artifact
    from nodebased.scene_state import read_scene_state
    return read_scene_state, read_control_bundle, _unpack_artifact


def camera_fit(state, beauties):
    """The camera the verifier's own tracker fits to each picture: `{frame: (camera, rms, landmarks)}`.

    This is the call `verify_conditioning` makes (conditioning_verify._track_sequence), so the numbers are the
    verifier's; the report keeps only the errors, this keeps the fitted camera so travel can be read off it.
    """
    from nodebased import conditioning_verify as verify
    width, height = state["frames"][0].get("resolution", (1920, 1080))
    solved, failures, _ = verify._track_sequence(state, {f: {"beauty": b} for f, b in beauties.items()}, width, height)
    return solved, failures


def fit_report(state, solved, failures):
    """A verification-report-shaped dict (per-frame `bindings.camera`) plus the fitted travel along the commanded move."""
    from nodebased import conditioning_verify as verify
    frames, positions = [], {}
    first = np.asarray(state["frames"][0]["camera"].transform.position.array(), np.float64)
    last = np.asarray(state["frames"][-1]["camera"].transform.position.array(), np.float64)
    move = last - first
    commanded = float(np.linalg.norm(move))
    direction = move / commanded if commanded > 1e-9 else None
    for row in state["frames"]:
        number = int(row["frame"])
        if number in solved:
            fitted, rms, landmarks = solved[number]
            camera = verify._camera_measurement(row["camera"], fitted)
            camera.update(tracker_landmarks=landmarks, tracker_reprojection_rms_pixels=rms)
            position = np.asarray(fitted.transform.position.array(), np.float64)
            positions[number] = position
            offset = position - first
            camera["fitted_travel"] = float(offset @ direction) if direction is not None else float(np.linalg.norm(offset))
            camera["fitted_position"] = [float(v) for v in position]
        else:
            camera = {"position_error_m": None, "rotation_error_degrees": None, "fov_error_degrees": None,
                      "reason": failures.get(number, "camera solve missing")}
        frames.append({"frame": number, "bindings": {"camera": camera}})
    return {"frames": frames}, commanded


def travel_summary(report, commanded):
    rows = [f["bindings"]["camera"] for f in report["frames"]]
    solved = [r for r in rows[1:] if r.get("fitted_travel") is not None]
    return {"commanded_travel": commanded,
            "fitted_travel_last": solved[-1]["fitted_travel"] if solved else None,
            "fitted_travel_max": max(r["fitted_travel"] for r in solved) if solved else None,
            "fitted_travel_per_frame": [r.get("fitted_travel") for r in rows]}


def read_sequence(store, generated_sequence, folder):
    """The generated frames' RGBA pictures in frame order."""
    import io
    import zipfile
    from nodebased.conditioned_read import _read_rgba
    blob = store.get(generated_sequence)
    pictures = []
    with zipfile.ZipFile(io.BytesIO(blob)) as archive:
        for name in sorted(n for n in archive.namelist() if n.endswith(".exr")):
            exr = folder / "frames" / name
            exr.parent.mkdir(parents=True, exist_ok=True)
            exr.write_bytes(archive.read(name))
            pictures.append(_read_rgba(exr)[0])
    return pictures


def scale_tag(scale):
    return "" if scale is None else f"@{scale:g}"


def run_one(model, path, work, scale=None, log=print):
    provider, frames, info_env = MODELS[model]
    scale = scale if model == "cameractrl" else None
    name = f"{model}-{path}{scale_tag(scale)}"
    folder = Path(work) / name
    folder.mkdir(parents=True, exist_ok=True)
    size = SIZES[model]
    keys = camera_keys(path, frames)
    graph = folder / "shot.nbcomp"
    shot.save_graph(graph, size[0], size[1], keys, frames, plate_folder=folder / "plate")
    info_file = folder / "run-info.json"
    info_file.unlink(missing_ok=True)
    os.environ[info_env] = str(info_file)
    agent = run_by_hand.Agent(graph, folder / "store")
    started = time.perf_counter()
    try:
        exported = agent.call(op="export_conditioning", id="export", first=1, last=frames)
        settings = {"sampler_settings": {"translation_scale": scale}} if scale is not None else {}
        generated = agent.call(op="generate", scene_state=exported["scene_state"], bundle=exported["control_bundle"],
                               provider=provider, seed=SEED, options={}, **settings)
        wall = time.perf_counter() - started
        verified = agent.call(op="verify", scene_state=exported["scene_state"], bundle=exported["control_bundle"],
                              generated_sequence=generated["generated_sequence"])
    finally:
        agent.close()
    from nodebased.artifacts import ArtifactStore
    store = ArtifactStore(root=folder / "store" / "artifacts")
    report = json.loads(store.get(verified["report"]))
    read_scene_state, _, unpack = scene_tools()
    scene_dir = folder / "scene"
    scene_dir.mkdir(exist_ok=True)
    state = read_scene_state(unpack(store.get(exported["scene_state"]), scene_dir))
    solved, failures = camera_fit(state, dict(zip((int(r["frame"]) for r in state["frames"]),
                                                    read_sequence(store, generated["generated_sequence"], folder))))
    fitted, commanded = fit_report(state, solved, failures)
    result = {"model": model, "provider": provider, "path": path, "translation_scale_setting": scale, "seed": SEED,
              "plate_size": list(size), "frame_count": frames,
              "camera_honoured": "camera_pose" in generated["controls"]
              and generated["controls"]["camera_pose"] == "used",
              "generate_and_export_wall_seconds": round(wall, 1),
              "model_run": json.loads(info_file.read_text()) if info_file.exists() else None,
              "generated_sequence": generated["generated_sequence"], "scene_state": exported["scene_state"],
              "verification_report": verified["report"],
              "camera": summarise(report), "travel": travel_summary(fitted, commanded),
              "static_camera_reference": static_camera_reference(keys)}
    used = (result["model_run"] or {}).get("translation_scale")
    log(f"{model:11s} {path:8s}{scale_tag(scale):8s} frames {frames:2d}  solved {result['camera']['solved_frames']:2d}  "
        f"rotation mean {result['camera']['rotation_error_degrees']['mean']}  "
        f"position mean {result['camera']['position_error']['mean']}  travel {result['travel']['fitted_travel_last']} "
        f"of {commanded:g}  scale used {used}  wall {wall:.0f} s")
    return result, folder


def srgb8_round_trip(rgba):
    """What every picture of a generative model goes through: scene-linear to 8-bit display sRGB and back."""
    from nodebased import color
    from nodebased.providers.sdxl_controlnet import srgb_to_acescg
    work = np.asarray(rgba, np.float32).copy()
    work[..., 3] = 1
    color.processor(color.WORKING, color.INPUT_SPACES["sRGB"]).applyRGBA(work)
    return srgb_to_acescg(np.rint(np.clip(work[..., :3], 0, 1) * 255).astype(np.uint8))


def floor_one(path, work, log=print):
    """The camera check on the exported beauty frames themselves: the score of a follower that is exact.

    Two readings: the beauty as exported, and the same pictures after the 8-bit sRGB round trip every generated
    picture goes through. Neither involves a model or the GPU.
    """
    folder = Path(work) / f"floor-{path}"
    folder.mkdir(parents=True, exist_ok=True)
    frames = MODELS["cameractrl"][1]
    keys = camera_keys(path, frames)
    graph = folder / "shot.nbcomp"
    shot.save_graph(graph, SIZES["cameractrl"][0], SIZES["cameractrl"][1], keys, frames, plate_folder=folder / "plate")
    agent = run_by_hand.Agent(graph, folder / "store")
    try:
        exported = agent.call(op="export_conditioning", id="export", first=1, last=frames)
    finally:
        agent.close()
    from nodebased.artifacts import ArtifactStore
    store = ArtifactStore(root=folder / "store" / "artifacts")
    read_scene_state, read_control_bundle, unpack = scene_tools()
    scene_dir, bundle_dir = folder / "scene", folder / "bundle"
    scene_dir.mkdir(exist_ok=True)
    bundle_dir.mkdir(exist_ok=True)
    scene_path = unpack(store.get(exported["scene_state"]), scene_dir)
    manifest = unpack(store.get(exported["control_bundle"]), bundle_dir)
    state = read_scene_state(scene_path)
    controls = read_control_bundle(manifest, scene_path)
    beauties = {c.frame: np.asarray(c.beauty.values, np.float32) for c in controls}
    out = {"path": path, "frame_count": frames, "plate_size": list(SIZES["cameractrl"]), "variants": {}}
    for variant, pictures in (("exported_beauty", beauties),
                              ("srgb8_round_trip", {f: srgb8_round_trip(b) for f, b in beauties.items()})):
        solved, failures = camera_fit(state, pictures)
        fitted, commanded = fit_report(state, solved, failures)
        out["variants"][variant] = {"camera": summarise(fitted), "travel": travel_summary(fitted, commanded)}
        c = out["variants"][variant]["camera"]
        log(f"floor {path:8s} {variant:17s} solved {c['solved_frames']:2d}  rotation mean {c['rotation_error_degrees']['mean']}"
            f"  position mean {c['position_error']['mean']}  travel {out['variants'][variant]['travel']['fitted_travel_last']}")
    return out


def resummarise(work, out):
    """Rebuild each run's camera summary from the verification report kept in its artifact store."""
    from nodebased.artifacts import ArtifactStore
    for path in sorted(Path(out).glob("*.json")):
        result = json.loads(path.read_text())
        folder = Path(work) / f"{result['model']}-{result['path']}{scale_tag(result.get('translation_scale_setting'))}"
        store = ArtifactStore(root=folder / "store" / "artifacts")
        report_id = result.get("verification_report") or next(
            m.name.split(".")[0] for m in (folder / "store" / "artifacts" / "metadata").glob("*")
            if json.loads(m.read_text()).get("kind") == "verification_report")
        result["verification_report"] = report_id
        result["camera"] = summarise(json.loads(store.get(report_id)))
        result["static_camera_reference"] = static_camera_reference(
            camera_keys(result["path"], result["frame_count"]))
        path.write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")
        print(f"{result['model']:11s} {result['path']:5s} solved {result['camera']['solved_frames']}/{result['camera']['frames']}  "
              f"rotation {result['camera']['rotation_error_degrees']}  position {result['camera']['position_error']}")


def contact_sheet(folder, generated_sequence, path):
    """First, middle and last generated frames side by side (display sRGB), for a look at the result."""
    import io
    import zipfile
    from nodebased.artifacts import ArtifactStore
    from nodebased.media import read_media_raster
    import OpenImageIO as oiio
    blob = ArtifactStore(root=folder / "store" / "artifacts").get(generated_sequence)
    frames = []
    with zipfile.ZipFile(io.BytesIO(blob)) as archive:
        names = sorted(n for n in archive.namelist() if n.endswith(".exr"))
        picks = [names[0], names[len(names) // 2], names[-1]]
        for name in picks:
            exr = folder / "frames" / name
            exr.parent.mkdir(parents=True, exist_ok=True)
            exr.write_bytes(archive.read(name))
            frames.append(np.rint(np.clip(np.array(read_media_raster(str(exr)).to_display()[..., :3]), 0, 1) * 255).astype(np.uint8))
    sheet = np.ascontiguousarray(np.concatenate(frames, axis=1))
    output = oiio.ImageOutput.create(str(path))
    output.open(str(path), oiio.ImageSpec(sheet.shape[1], sheet.shape[0], 3, oiio.UINT8))
    output.write_image(sheet)
    output.close()


def run_row(result):
    camera, run = result["camera"], result.get("model_run") or {}
    first = camera["per_frame"][0]
    return {"path": result["path"], "translation_scale_setting": result.get("translation_scale_setting"),
            "translation_scale_used": run.get("translation_scale"),
            "translation_scale_source": run.get("translation_scale_source"),
            "reference_median_depth": run.get("reference_median_depth"),
            "rotation_error_degrees": camera["rotation_error_degrees"], "position_error": camera["position_error"],
            "fov_error_degrees_mean": camera["fov_error_degrees_mean"],
            "commanded_travel": result["travel"]["commanded_travel"],
            "fitted_travel_last": result["travel"]["fitted_travel_last"],
            "static_camera_reference": result["static_camera_reference"],
            "first_frame_fit": {"position_error": first["position_error"],
                                "rotation_error_degrees": first["rotation_error_degrees"]},
            "model_seconds": run.get("generate_seconds"), "peak_vram_allocated_mib": run.get("peak_vram_allocated_mib"),
            "wall_seconds_export_and_generate": result["generate_and_export_wall_seconds"]}


def write_summary(out):
    """summary.json from the run files in `out`: the scale sweep, the default-scale runs and the floors."""
    out = Path(out)
    runs = [json.loads(p.read_text()) for p in sorted(out.glob("cameractrl-*.json"))]
    sweep = sorted((run_row(r) for r in runs if r.get("translation_scale_setting") is not None),
                   key=lambda row: -row["translation_scale_setting"])
    default = [run_row(r) for r in runs if r.get("translation_scale_setting") is None]
    floors = {}
    for p in sorted(out.glob("floor-*.json")):
        data = json.loads(p.read_text())
        floors[data["path"]] = {name: {"rotation_error_degrees": v["camera"]["rotation_error_degrees"],
                                       "position_error": v["camera"]["position_error"],
                                       "fov_error_degrees_mean": v["camera"]["fov_error_degrees_mean"]}
                                for name, v in data["variants"].items()}
    best = min(sweep, key=lambda row: row["position_error"]["mean"]) if sweep else None
    summary = {"summary": "errors are the mean over frames 2..N of the verifier's camera check (largest in 'max'); "
                          "frame 1 is the reference picture and is reported separately as first_frame_fit",
               "s_dolly": best and best["translation_scale_setting"], "scale_sweep_dolly": sweep,
               "default_scale_runs": default, "perfect_follower_floor": floors}
    (out / "summary.json").write_text(json.dumps(summary, indent=1) + "\n", encoding="utf-8")
    print(json.dumps({k: v for k, v in summary.items() if k != "summary"}, indent=1)[:4000])


def parse_scales(values):
    scales = []
    for value in values or []:
        for item in value.split(","):
            if item.strip():
                scales.append(float(item))
    return scales


def run_specs(runs, scales):
    """`model:path[@scale]` entries; every CameraCtrl entry without its own scale is repeated once per `--translation-scale`."""
    specs = []
    for spec in runs.split(","):
        name, _, own = spec.partition("@")
        model, path = name.split(":")
        if path not in PATHS:
            raise SystemExit(f"unknown path {path!r}; choose from {', '.join(PATHS)}")
        if model not in MODELS:
            raise SystemExit(f"unknown model {model!r}; choose from {', '.join(MODELS)}")
        if own:
            specs.append((model, path, float(own)))
        elif scales and model == "cameractrl":
            specs.extend((model, path, scale) for scale in scales)
        else:
            specs.append((model, path, None))
    return specs


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--work", required=True, help="scratch folder (stores, frames); never /tmp")
    parser.add_argument("--out", required=True, help="folder for the benchmark JSON and contact sheets")
    parser.add_argument("--runs", default="cameractrl:dolly,cameractrl:pan,svd:dolly,svd:pan")
    parser.add_argument("--translation-scale", action="append", metavar="S[,S...]",
                        help="CameraCtrl translation_scale sampler setting; repeat or comma-separate to sweep")
    parser.add_argument("--floor", metavar="PATHS", help="comma list of paths: the camera check on the exported beauty "
                        "frames themselves (no model, no GPU); writes floor-PATH.json")
    parser.add_argument("--summary", action="store_true", help="write summary.json from the run files in --out")
    parser.add_argument("--resummarise", action="store_true", help="re-read the reports of finished runs; generate nothing")
    args = parser.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    if args.resummarise:
        resummarise(args.work, out)
        return 0
    if args.summary:
        write_summary(out)
        return 0
    if args.floor:
        for path in args.floor.split(","):
            result = floor_one(path, args.work)
            (out / f"floor-{path}.json").write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")
        return 0
    for model, path, scale in run_specs(args.runs, parse_scales(args.translation_scale)):
        result, folder = run_one(model, path, args.work, scale)
        name = f"{model}-{path}{scale_tag(scale)}"
        (out / f"{name}.json").write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")
        contact_sheet(folder, result["generated_sequence"], Path(args.work) / f"{name}-sheet.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())

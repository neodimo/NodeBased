"""Does the video model follow the exported camera? Dolly and pan paths on the demo scene, two models.

For each path (a straight dolly forward by one scene unit, a pan of 20 degrees with the position fixed) the
demo shot's graph is built with that camera path, the SceneState and ControlBundle are exported, the shot is
generated by a provider with the same reference frame and seed, and the verifier's camera check measures the
camera the generated pictures show against the exported camera on every frame:

    python examples/demo_shot/benchmark_camera_following.py --work DIR --out DIR [--runs cameractrl:dolly,...]

`cameractrl_svd` (CameraCtrl on SVD-XT) takes the camera and makes 25 frames at 576 x 320. `svd_image_video`
(step A, the control) ignores the camera and is limited to eight frames on this card, so its path covers the
same total move in eight frames, on a 16:9 plate. The camera check's measurement is kept in the report for a provider that
does not honour the camera; nothing here changes the verdict.
"""
from __future__ import annotations

import argparse
import json
import math
import os
import sys
import time
from pathlib import Path

import numpy as np

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import shot  # noqa: E402
import run_by_hand  # noqa: E402

REPO = shot.HERE.parents[1]
sys.path.insert(0, str(REPO))
# CameraCtrl generates at 576 x 320. step A's adapter resizes to 1024 x 576 (16:9), so its control runs on the 16:9
# plate 576 x 324: a 576 x 320 plate would be stretched by 1.2 percent each way and the camera fit would read it
# as a rotation error on the reference frame itself.
SIZES = {"cameractrl": (576, 320), "svd": (576, 324)}
SEED = 7
MODELS = {"cameractrl": ("cameractrl_svd", 25, "NODEBASED_CAMERACTRL_RUN_INFO"),
          "svd": ("svd_image_video", 8, "NODEBASED_SVD_RUN_INFO")}
DOLLY_UNITS = 1.0
PAN_DEGREES = 20.0


def camera_keys(path, frames):
    """Camera parameters for each frame: the move spans the whole clip, whatever its length."""
    start = shot.CAMERA_START
    eye = np.array((start["tx"], start["ty"], start["tz"]))
    target = np.array((start["target_x"], start["target_y"], start["target_z"]))
    forward = (target - eye) / np.linalg.norm(target - eye)
    keys = {}
    for frame in range(1, frames + 1):
        t = (frame - 1) / max(frames - 1, 1)
        if path == "dolly":
            position, aim = eye + forward * DOLLY_UNITS * t, target + forward * DOLLY_UNITS * t
        elif path == "pan":
            angle = math.radians(PAN_DEGREES * t)  # a positive turn about +Y looks to the left
            rotation = np.array(((math.cos(angle), 0, math.sin(angle)), (0, 1, 0), (-math.sin(angle), 0, math.cos(angle))))
            position, aim = eye, eye + rotation @ (target - eye)
        else:
            raise ValueError(path)
        keys[frame] = dict(tx=position[0], ty=position[1], tz=position[2], target_x=aim[0], target_y=aim[1],
                           target_z=aim[2], roll=0.0, focal=shot.FOCAL)
    return keys


def static_camera_reference(keys):
    """What a camera that never leaves frame 1 would score against the path: the size of the move itself."""
    def parts(key):
        eye = np.array((key["tx"], key["ty"], key["tz"]))
        aim = np.array((key["target_x"], key["target_y"], key["target_z"])) - eye
        return eye, aim / np.linalg.norm(aim)
    first_eye, first_aim = parts(keys[1])
    rows = []
    for frame in sorted(keys)[1:]:
        eye, aim = parts(keys[frame])
        rows.append((float(np.linalg.norm(eye - first_eye)), float(np.degrees(np.arccos(np.clip(first_aim @ aim, -1, 1))))))
    return {"position_error_mean": float(np.mean([r[0] for r in rows])), "position_error_last": rows[-1][0],
            "rotation_error_degrees_mean": float(np.mean([r[1] for r in rows])), "rotation_error_degrees_last": rows[-1][1]}


def summarise(report, first_frame_is_reference=True):
    rows = []
    for frame in report["frames"]:
        camera = (frame.get("bindings") or {}).get("camera") or {}
        rows.append({"frame": frame.get("frame"), "position_error": camera.get("position_error_m"),
                     "rotation_error_degrees": camera.get("rotation_error_degrees"),
                     "fov_error_degrees": camera.get("fov_error_degrees"),
                     "tracker_landmarks": camera.get("tracker_landmarks"),
                     "reprojection_rms_pixels": camera.get("tracker_reprojection_rms_pixels"),
                     "reason": camera.get("reason")})
    moving = [r for r in rows[1:] if r["rotation_error_degrees"] is not None] if first_frame_is_reference else \
        [r for r in rows if r["rotation_error_degrees"] is not None]

    def stat(name, function):
        values = [r[name] for r in moving]
        return float(function(values)) if values else None
    return {"frames": len(rows), "solved_frames": len(moving),
            "rotation_error_degrees": {"mean": stat("rotation_error_degrees", np.mean),
                                       "max": stat("rotation_error_degrees", np.max),
                                       "last": moving[-1]["rotation_error_degrees"] if moving else None},
            "position_error": {"mean": stat("position_error", np.mean), "max": stat("position_error", np.max),
                               "last": moving[-1]["position_error"] if moving else None},
            "fov_error_degrees_mean": stat("fov_error_degrees", np.mean), "per_frame": rows}


def run_one(model, path, work, log=print):
    provider, frames, info_env = MODELS[model]
    folder = Path(work) / f"{model}-{path}"
    folder.mkdir(parents=True, exist_ok=True)
    size = SIZES[model]
    keys = camera_keys(path, frames)
    graph = folder / "shot.nbcomp"
    shot.save_graph(graph, size[0], size[1], keys, frames, plate_folder=folder / "plate")
    info_file = folder / "run-info.json"
    info_file.unlink(missing_ok=True)
    os.environ[info_env] = str(info_file)
    agent = run_by_hand.Agent(graph, folder / "store")
    started = time.perf_counter()
    try:
        exported = agent.call(op="export_conditioning", id="export", first=1, last=frames)
        generated = agent.call(op="generate", scene_state=exported["scene_state"], bundle=exported["control_bundle"],
                               provider=provider, seed=SEED, options={})
        wall = time.perf_counter() - started
        verified = agent.call(op="verify", scene_state=exported["scene_state"], bundle=exported["control_bundle"],
                              generated_sequence=generated["generated_sequence"])
    finally:
        agent.close()
    from nodebased.artifacts import ArtifactStore
    report = json.loads(ArtifactStore(root=folder / "store" / "artifacts").get(verified["report"]))
    result = {"model": model, "provider": provider, "path": path, "seed": SEED, "plate_size": list(size),
              "frame_count": frames, "camera_honoured": "camera_pose" in generated["controls"]
              and generated["controls"]["camera_pose"] == "used",
              "generate_and_export_wall_seconds": round(wall, 1),
              "model_run": json.loads(info_file.read_text()) if info_file.exists() else None,
              "generated_sequence": generated["generated_sequence"], "scene_state": exported["scene_state"],
              "verification_report": verified["report"],
              "camera": summarise(report), "static_camera_reference": static_camera_reference(keys)}
    log(f"{model:11s} {path:5s} frames {frames:2d}  solved {result['camera']['solved_frames']:2d}  "
        f"rotation mean {result['camera']['rotation_error_degrees']['mean']}  "
        f"position mean {result['camera']['position_error']['mean']}  wall {wall:.0f} s")
    return result, folder


def resummarise(work, out):
    """Rebuild each run's camera summary from the verification report kept in its artifact store."""
    from nodebased.artifacts import ArtifactStore
    for path in sorted(Path(out).glob("*.json")):
        result = json.loads(path.read_text())
        folder = Path(work) / f"{result['model']}-{result['path']}"
        store = ArtifactStore(root=folder / "store" / "artifacts")
        report_id = result.get("verification_report") or next(
            m.name.split(".")[0] for m in (folder / "store" / "artifacts" / "metadata").glob("*")
            if json.loads(m.read_text()).get("kind") == "verification_report")
        result["verification_report"] = report_id
        result["camera"] = summarise(json.loads(store.get(report_id)))
        result["static_camera_reference"] = static_camera_reference(
            camera_keys(result["path"], result["frame_count"]))
        path.write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")
        print(f"{result['model']:11s} {result['path']:5s} solved {result['camera']['solved_frames']}/{result['camera']['frames']}  "
              f"rotation {result['camera']['rotation_error_degrees']}  position {result['camera']['position_error']}")


def contact_sheet(folder, generated_sequence, path):
    """First, middle and last generated frames side by side (display sRGB), for a look at the result."""
    import io
    import zipfile
    from nodebased.artifacts import ArtifactStore
    from nodebased.media import read_media_raster
    import OpenImageIO as oiio
    blob = ArtifactStore(root=folder / "store" / "artifacts").get(generated_sequence)
    frames = []
    with zipfile.ZipFile(io.BytesIO(blob)) as archive:
        names = sorted(n for n in archive.namelist() if n.endswith(".exr"))
        picks = [names[0], names[len(names) // 2], names[-1]]
        for name in picks:
            exr = folder / "frames" / name
            exr.parent.mkdir(parents=True, exist_ok=True)
            exr.write_bytes(archive.read(name))
            frames.append(np.rint(np.clip(np.array(read_media_raster(str(exr)).to_display()[..., :3]), 0, 1) * 255).astype(np.uint8))
    sheet = np.ascontiguousarray(np.concatenate(frames, axis=1))
    output = oiio.ImageOutput.create(str(path))
    output.open(str(path), oiio.ImageSpec(sheet.shape[1], sheet.shape[0], 3, oiio.UINT8))
    output.write_image(sheet)
    output.close()


def main():
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--work", required=True, help="scratch folder (stores, frames); never /tmp")
    parser.add_argument("--out", required=True, help="folder for the benchmark JSON and contact sheets")
    parser.add_argument("--runs", default="cameractrl:dolly,cameractrl:pan,svd:dolly,svd:pan")
    parser.add_argument("--resummarise", action="store_true", help="re-read the reports of finished runs; generate nothing")
    args = parser.parse_args()
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)
    if args.resummarise:
        resummarise(args.work, out)
        return 0
    for spec in args.runs.split(","):
        model, path = spec.split(":")
        result, folder = run_one(model, path, args.work)
        (out / f"{model}-{path}.json").write_text(json.dumps(result, indent=1) + "\n", encoding="utf-8")
        contact_sheet(folder, result["generated_sequence"], Path(args.work) / f"{model}-{path}-sheet.png")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
